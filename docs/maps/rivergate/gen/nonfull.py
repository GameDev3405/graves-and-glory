"""Inventory of blocks that are not full cubes, for the map review. Usage: python nonfull.py OUT.md
Levels: 'floor' = the ground surface itself (y = column height), 'feet' = one above the ground, 'head' = two above,
'high' = anything higher. Floor and feet are where troops and players meet them."""
import sys, re, collections
import rgmap

KINDS = [('slab', r'_slab$'), ('stairs', r'_stairs$'), ('trapdoor', r'trapdoor$'), ('fence gate', r'fence_gate$'), ('fence', r'_fence$'),
         ('wall', r'_wall$'), ('bars and panes', r'iron_bars$|glass_pane$'), ('carpet', r'carpet$'), ('pressure plate', r'pressure_plate$'),
         ('door', r'_door$'), ('banner', r'banner$'), ('chain', r'^chain$'), ('lantern', r'lantern$'), ('campfire', r'campfire$'),
         ('bed', r'_bed$'), ('ladder', r'^ladder$'), ('path and farmland', r'^dirt_path$|^farmland$'), ('mud (short)', r'^mud$|^soul_sand$'),
         ('plants', r'^(grass|tall_grass|fern|large_fern|poppy|dandelion|cornflower|oxeye_daisy|azure_bluet|allium|wheat|carrots|potatoes|beetroots|sweet_berry_bush|lily_pad|sugar_cane|vine|dead_bush|.*_sapling|.*tulip|lilac|rose_bush|peony|moss_carpet|seagrass|kelp.*)$'),
         ('leaves', r'leaves$'), ('workstations and props', r'^(cauldron|water_cauldron|grindstone|anvil|chest|bell|lectern|brewing_stand|composter|stonecutter|lightning_rod|flower_pot|potted_.*|scaffolding|cobweb|torch|wall_torch|candle|.*_candle|end_rod|hopper|loom|.*_sign|.*_hanging_sign|bamboo|pointed_dripstone|conduit|enchanting_table|.*head|.*skull|turtle_egg|sea_pickle|snow|cake)$')]
FULLISH = re.compile(r'^(air|water|.*_planks|.*_log|.*_wood|stone.*|cobblestone|mossy_cobblestone|.*bricks|.*terracotta|.*concrete|.*wool|grass_block|dirt|coarse_dirt|podzol|rooted_dirt|gravel|sand|clay|packed_mud|andesite|diorite|granite|polished_.*|deepslate.*|hay_block|barrel|bookshelf|.*_tiles|smooth_.*|chiseled_.*|cut_.*|tuff|calcite|moss_block|crafting_table|furnace|smoker|blast_furnace|melon|pumpkin|.*_ore|bricks|mud_bricks|cracked_.*|mossy_stone_bricks|jack_o_lantern|glass|.*_glass|note_block|fletching_table|cartography_table|smithing_table|sponge|target|bee_nest|beehive|dried_kelp_block|bone_block|iron_block|coal_block|.*_block)$')


def kind(name):
    if name.endswith('_slab') or name.endswith('_stairs') or name.endswith('_wall'): pass
    for k, pat in KINDS:
        if re.search(pat, name): return k
    return None if FULLISH.match(name) else 'other: ' + name


def section(x, z):
    return 'ABCDEFGHI'[(x - rgmap.X0) // 64] + str((z - rgmap.Z0) // 64 + 1)


if __name__ == '__main__':
    m = rgmap.Map()
    cells = m.cells((rgmap.X0, rgmap.YLO, rgmap.Z0), (rgmap.X1, rgmap.YHI + 8, rgmap.Z1), solid=False)
    by = collections.defaultdict(lambda: collections.Counter())          # kind -> level -> n
    names = collections.defaultdict(collections.Counter)
    low = collections.defaultdict(lambda: collections.defaultdict(list))  # kind -> section -> positions at floor/feet
    open_low = collections.defaultdict(list)                              # floor/feet items with open sky above (outdoors)
    for (x, y, z), b in cells.items():
        if not (rgmap.X0 <= x <= rgmap.X1 and rgmap.Z0 <= z <= rgmap.Z1): continue
        name = b.split('[')[0].replace('minecraft:', '')
        k = kind(name)
        if not k: continue
        h = m.col[(x, z)][0]
        if m.col[(x, z)][2] == 'water': h = max(h, 62)
        lvl = 'floor' if y <= h else 'feet' if y == h + 1 else 'head' if y == h + 2 else 'high'
        if k in ('slab', 'stairs', 'trapdoor', 'carpet', 'pressure plate', 'path and farmland', 'mud (short)', 'campfire', 'bed') or lvl in ('floor', 'feet'):
            # relative to what is under it: a slab on a house floor is 'feet' for someone indoors
            under = cells.get((x, y - 1, z)); under2 = cells.get((x, y - 2, z))
            if lvl in ('head', 'high') and under and not kind(under.split('[')[0].replace('minecraft:', '')) and under.split('[')[0] not in ('air', 'water') and cells.get((x, y + 1, z), 'air').startswith('air') :
                lvl = 'on a raised floor'
        by[k][lvl] += 1; names[k][b] += 1
        if lvl in ('floor', 'feet'):
            low[k][section(x, z)].append((x, y, z))
            if not any((x, yy, z) in cells and not cells[(x, yy, z)].startswith('air') for yy in range(y + 1, y + 30)): open_low[k].append((x, y, z, b))
    out = ['# Rivergate: blocks that are not full cubes', '',
           'Generated by gen/nonfull.py from the map generator. World y = map y + 135 in the test world (ground 64 -> 199).',
           'Levels: floor = the ground surface itself; feet = one above the ground; head = two above; on a raised floor = sits on a solid block above ground with air over it (house floors, wall walks, decks); high = anything else higher up.', '',
           '## Counts by kind and level', '', '| kind | floor | feet | head | raised floor | high | total |', '|---|---|---|---|---|---|---|']
    for k in sorted(by, key=lambda k: -sum(by[k].values())):
        c = by[k]; out.append('| %s | %d | %d | %d | %d | %d | %d |' % (k, c['floor'], c['feet'], c['head'], c['on a raised floor'], c['high'], sum(c.values())))
    out += ['', '## At floor or feet level, by kind: sections and sample positions (map x y z)', '']
    for k in sorted(low, key=lambda k: -sum(len(v) for v in low[k].values())):
        if k in ('plants', 'leaves'):
            out.append('- **%s**: %d (pass-through or decorative; not listed)' % (k, sum(len(v) for v in low[k].values()))); continue
        out.append('### %s (%d)' % (k, sum(len(v) for v in low[k].values())))
        out.append('states: ' + ', '.join('%s x%d' % (s, n) for s, n in names[k].most_common(8)))
        for s in sorted(low[k]):
            ps = low[k][s]
            out.append('- %s: %d, e.g. %s' % (s, len(ps), '; '.join('%d %d %d' % p for p in ps[:4])))
        out.append('')
    out += ['## Outdoors at floor or feet level (open sky above): the ones most likely to trip troops', '']
    for k in sorted(open_low, key=lambda k: -len(open_low[k])):
        if k in ('plants', 'leaves'): continue
        c = collections.Counter(b for *_, b in open_low[k])
        out.append('- **%s**: %d. %s' % (k, len(open_low[k]), ', '.join('%s x%d' % (s, n) for s, n in c.most_common(6))))
    open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
    print(sys.argv[1], sum(sum(c.values()) for c in by.values()), 'non-full blocks')
    for k in sorted(by, key=lambda k: -sum(by[k].values())): print(' ', k, dict(by[k]))
