#!/usr/bin/env python3
"""Balance method: fight plans and analysis for DuelSimulation (unit duels and army clashes) and BotSimulation (bot matches).

    python tools/balance_method.py plan-units --out FILE [--reps 6] [--mirror-reps 8] [--calib-reps 2] [--types a,b,...] [--only t1,t2] [--cap 120]
    python tools/balance_method.py plan-clashes --out FILE [--reps 16] [--houses gilded,graveborn,ironclad,tidecallers] [--cap 150]
    python tools/balance_method.py units DUELS.csv [DUELS.csv ...] [--matrix] [--boot 1000]
    python tools/balance_method.py units DUELS.csv [...] --json OUT.json     (also writes the ratings as JSON)
    python tools/balance_method.py compare --a DUELS.csv[,DUELS.csv] --b DUELS.csv[,DUELS.csv] [--focus troop] [--own-se | --null-a .. --null-b ..]
    python tools/balance_method.py compare-matches --a RESULTS.csv[,..] --b RESULTS.csv[,..] --focus <botBanners id>
    python tools/balance_method.py rr FILE [FILE ...]          (botsim results.csv or duel duels.csv of banner:<id> clashes)
    python tools/balance_method.py types TYPES.csv [TYPES.csv ...] [--results RESULTS.csv ...]
    python tools/balance_method.py gate

Unit duel model (one row per fight; A and B are one troop type each, at equal gold): the margin m = (gold left, health-weighted, as a share of
A's start) - (the same for B), in [-1, 1]. Least squares m = r_A - r_B + beta ln(G_A/G_B) + gamma side + e, side +1 when A stood west,
with the ratings r summing to 0 over the types in the run: r is how much of its own gold a type keeps over its opponent's, averaged over
the field, so no single unit is the anchor. beta comes mostly from the calibration fights (a type against itself at about 1.25 times the
count). 95% intervals: bootstrap over fights within each pairing.

Round robin (matches or clashes): Bradley-Terry with a seat term, logit P(team 0 wins) = s_i - s_j + h, draws count half, the s summing to 0;
standard errors from the information matrix; a likelihood-ratio test of one rating per House against one free share per pair. The mean
score gap (matches) or margin (clashes) gets the same additive model by least squares.
"""
import argparse
import collections
import csv
import itertools
import json
import math
import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
DUEL_TYPES = ['knight', 'archer', 'sentinel', 'longbow', 'revenant', 'bonebow', 'reaper', 'stalker', 'hexer',
              'ic_hearthguard', 'ic_arbalist', 'ic_breaker', 'ic_ballista', 'ic_mortar',
              'tc_raider', 'tc_harpooner', 'tc_tideguard', 'tc_brute']
HOUSES = ['gilded', 'graveborn', 'ironclad', 'tidecallers']


def sheet():
    return json.loads((ROOT / 'sheets/design.json').read_text(encoding='utf-8'))


def troops():
    return {t['id']: t for t in sheet()['troops']}


def read_csv(paths):
    rows = []
    for p in paths:
        with open(p, newline='', encoding='utf-8') as f:
            for r in csv.DictReader(f):
                r['_file'] = str(p)
                rows.append(r)
    return rows


def split_paths(text):
    return [p for p in text.split(',') if p]


# ---------------------------------------------------------------- plans

def best_counts(ca, cb, lo, hi):
    best = None
    for na in range(1, 80):
        for nb in range(1, 80):
            ga, gb = na * ca, nb * cb
            if not (lo <= ga <= hi and lo <= gb <= hi):
                continue
            mis = abs(ga - gb) / ((ga + gb) / 2)
            key = (round(mis, 3), abs((ga + gb) / 2 - (lo + hi) / 2))
            if best is None or key < best[0]:
                best = (key, na, nb)
    return best[1], best[2]


def plan_units(args):
    T = troops()
    types = args.types.split(',') if args.types else DUEL_TYPES
    only = set(args.only.split(',')) if args.only else None
    opts = f'traits=banner;charge=0;cap={args.cap};distance=28'
    lines = [f'# unit duels: {len(types)} types, equal gold {args.lo} to {args.hi}; generated by tools/balance_method.py plan-units']
    for a, b in itertools.combinations(types, 2):
        if only and a not in only and b not in only:
            continue
        na, nb = best_counts(T[a]['cost'], T[b]['cost'], args.lo, args.hi)
        lines.append(f'{a}~{b}|{a}*{na}|{b}*{nb}|{args.reps}|{opts}')
    for a in types:
        if only and a not in only:
            continue
        n = max(1, round(((args.lo + args.hi) / 2) / T[a]['cost']))
        if args.mirror_reps:
            lines.append(f'{a}~{a}|{a}*{n}|{a}*{n}|{args.mirror_reps}|{opts}')
        if args.calib_reps:
            m = max(n + 1, round(n * 1.25))
            lines.append(f'{a}^{a}|{a}*{m}|{a}*{n}|{args.calib_reps}|{opts}')
    pathlib.Path(args.out).write_text('\n'.join(lines) + '\n', encoding='utf-8')
    fights = sum(int(l.split('|')[3]) for l in lines if not l.startswith('#'))
    print(f'{args.out}: {len(lines) - 1} pairings, {fights} fights')


def plan_clashes(args):
    houses = args.houses.split(',')
    opts = f'traits=live;charge=1;cap={args.cap};distance=40'
    lines = ['# army clashes: one <house>_normal army against another, no points; generated by tools/balance_method.py plan-clashes']
    for a, b in itertools.combinations(houses, 2):
        lines.append(f'{a}~{b}|banner:{a}_normal|banner:{b}_normal|{args.reps}|{opts}')
    for a in houses:
        lines.append(f'{a}~{a}|banner:{a}_normal|banner:{a}_normal|{args.mirror_reps}|{opts}')
    pathlib.Path(args.out).write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{args.out}: {len(lines) - 1} pairings, {sum(int(l.split("|")[3]) for l in lines[1:])} fights')


# ---------------------------------------------------------------- unit duels

def mono(label):
    """The troop of a one-type lineup ('reaper*6'), else None."""
    if label.startswith('banner:') or '+' in label:
        return None
    return label.split('*')[0]


def duel_rows(paths):
    out = []
    for r in read_csv(paths):
        if r['winner'] == 'aborted':
            continue
        a, b = mono(r['aLineup']), mono(r['bLineup'])
        if a is None or b is None:
            continue
        out.append(dict(a=a, b=b, id=r['id'], m=float(r['margin']), side=1 if r['aSide'] == 'west' else -1,
                        g=math.log(float(r['aStartGold']) / float(r['bStartGold'])),
                        win=1.0 if r['winner'] == 'a' else 0.5 if r['winner'] == 'draw' else 0.0,
                        end=r['end'], seconds=float(r['seconds']), wall=float(r['wallSeconds'])))
    return out


def fit_units(rows, types):
    idx = {t: i for i, t in enumerate(types)}
    k = len(types)
    X = np.zeros((len(rows) + 1, k + 2))
    y = np.zeros(len(rows) + 1)
    for n, r in enumerate(rows):
        if r['a'] != r['b']:
            X[n, idx[r['a']]] += 1
            X[n, idx[r['b']]] -= 1
        X[n, k] = r['g']
        X[n, k + 1] = r['side']
        y[n] = r['m']
    X[-1, :k] = 1  # the ratings sum to 0
    coef, *_ = np.linalg.lstsq(X, y, rcond=None)
    return coef[:k], coef[k], coef[k + 1]


def unit_ratings(rows, boot=1000, seed=1):
    types = [t for t in DUEL_TYPES if any(r['a'] == t or r['b'] == t for r in rows)]
    types += sorted(({r['a'] for r in rows} | {r['b'] for r in rows}) - set(types))
    r0, beta, gamma = fit_units(rows, types)
    # Resample within pairing and side: each pairing has its own west/east lean that recurs in every run (the per-cell side effect
    # correlated +0.16 to +0.64 between runs), so it is part of the cell, not noise. Resampling across sides counted it as noise.
    # A side with one fight in a pairing (the calibration fights) is pooled with the other side. With 2 fights per stratum a plain
    # bootstrap gives half the variance (factor (n-1)/n), so each resampled margin is moved away from its stratum mean by sqrt(n/(n-1))
    # (the rescaled bootstrap). Calibrated against two unchanged runs with different seeds (report: noise check).
    count = collections.Counter((r['id'], r['side']) for r in rows)
    groups = collections.defaultdict(list)
    for n, r in enumerate(rows):
        groups[(r['id'], r['side']) if count[(r['id'], r['side'])] > 1 else r['id']].append(n)
    strata = [np.array(v) for v in groups.values()]
    y = np.array([r['m'] for r in rows])
    rng = np.random.default_rng(seed)
    samples = []
    for _ in range(boot):
        pick, ys = [], []
        for ix in strata:
            j = ix[rng.integers(0, len(ix), len(ix))]
            if len(ix) > 1:
                mu = y[ix].mean()
                ys.append(mu + math.sqrt(len(ix) / (len(ix) - 1)) * (y[j] - mu))
            else:
                ys.append(y[j])
            pick.append(j)
        pick, ys = np.concatenate(pick), np.concatenate(ys)
        sample = [dict(rows[j], m=v) for j, v in zip(pick, ys)]
        r, b, g = fit_units(sample, types)
        samples.append(list(r) + [b, g])
    S = np.array(samples)
    se = S.std(axis=0, ddof=1)
    lo, hi = np.percentile(S, 2.5, axis=0), np.percentile(S, 97.5, axis=0)
    return dict(types=types, r=r0, beta=beta, gamma=gamma, se=se[:len(types)], lo=lo[:len(types)], hi=hi[:len(types)],
                beta_se=se[len(types)], gamma_se=se[len(types) + 1], boot=S)


def pair_cells(rows):
    cells = collections.defaultdict(list)
    for r in rows:
        if r['a'] == r['b']:
            continue
        a, b = sorted((r['a'], r['b']))
        sign = 1 if r['a'] == a else -1
        cells[(a, b)].append((sign * r['m'], r['win'] if sign == 1 else 1 - r['win']))
    out = {}
    for key, v in cells.items():
        m = np.array([x[0] for x in v])
        w = np.array([x[1] for x in v])
        out[key] = dict(n=len(v), m=m.mean(), se=m.std(ddof=1) / math.sqrt(len(v)) if len(v) > 1 else float('nan'), win=w.mean())
    return out


def report_units(args):
    rows = duel_rows(args.files)
    if not rows:
        sys.exit('no unit duels in the files')
    T = troops()
    res = unit_ratings(rows, boot=args.boot)
    mirrors = [r for r in rows if r['a'] == r['b'] and abs(r['g']) < 1e-9]
    calib = [r for r in rows if r['a'] == r['b'] and abs(r['g']) > 1e-9]
    n_by = collections.Counter()
    win_by = collections.defaultdict(list)
    for r in rows:
        if r['a'] == r['b']:
            continue
        n_by[r['a']] += 1
        n_by[r['b']] += 1
        win_by[r['a']].append(r['win'])
        win_by[r['b']].append(1 - r['win'])
    ends = collections.Counter(r['end'] for r in rows)
    print(f'fights={len(rows)} (pairings {len({r["id"] for r in rows})}; mirrors {len(mirrors)}, calibration {len(calib)}); ends {dict(ends)}; '
          f'mean fight {np.mean([r["seconds"] for r in rows]):.1f} s game, {np.mean([r["wall"] for r in rows]):.2f} s wall')
    print(f'gold elasticity beta={res["beta"]:.3f} (SE {res["beta_se"]:.3f}): +10% gold moves the margin by {res["beta"] * math.log(1.1):+.3f}')
    print(f'side term gamma (A west)={res["gamma"]:+.4f} (SE {res["gamma_se"]:.4f})')
    if mirrors:
        mm = np.array([r['m'] * r['side'] for r in mirrors])  # west minus east
        print(f'mirrors: n={len(mirrors)}, mean west-minus-east margin {mm.mean():+.4f} (SE {mm.std(ddof=1) / math.sqrt(len(mm)):.4f}), '
              f'west won {sum(1 for r in mirrors if (r["win"] == 1) == (r["side"] == 1) and r["win"] != 0.5)} of {len(mirrors)}, draws {sum(1 for r in mirrors if r["win"] == 0.5)}')
    print()
    print(f'{"type":16s} {"house":11s} {"cost":>4s} {"n":>4s} {"rating":>7s} {"95% CI":>16s} {"value/gold":>10s} {"win%":>5s}')
    order = np.argsort(-res['r'])
    for i in order:
        t = res['types'][i]
        value = math.exp(res['r'][i] / res['beta']) if res['beta'] > 0.05 else float('nan')
        wins = 100 * np.mean(win_by[t]) if win_by[t] else float('nan')
        print(f'{t:16s} {T[t]["house"]:11s} {T[t]["cost"]:4d} {n_by[t]:4d} {res["r"][i]:+7.3f} [{res["lo"][i]:+.3f},{res["hi"][i]:+.3f}] {value:10.2f} {wins:5.1f}')
    by_house = collections.defaultdict(list)
    for i, t in enumerate(res['types']):
        by_house[T[t]['house']].append(i)
    print()
    for h, ix in by_house.items():
        vals = res['boot'][:, ix].mean(axis=1)
        print(f'house {h:11s} mean rating {res["r"][ix].mean():+.3f} [{np.percentile(vals, 2.5):+.3f},{np.percentile(vals, 97.5):+.3f}] over {len(ix)} types')
    if args.matrix:
        cells = pair_cells(rows)
        print('\npairing cells (mean margin of the first type, SE, win share, n):')
        for (a, b), c in sorted(cells.items()):
            print(f'  {a:15s} vs {b:15s} m={c["m"]:+.3f} se={c["se"]:.3f} win={c["win"]:.2f} n={c["n"]}')
    if args.json:
        pathlib.Path(args.json).write_text(json.dumps(dict(types=res['types'], r=res['r'].tolist(), se=res['se'].tolist(), lo=res['lo'].tolist(),
                                                           hi=res['hi'].tolist(), beta=res['beta'], gamma=res['gamma'], n=len(rows)), indent=1))


def compare(args):
    A, B = duel_rows(split_paths(args.a)), duel_rows(split_paths(args.b))
    # A rating depends on the opponents it was measured against, so both runs are cut to the pairings they share.
    ids = {r['id'] for r in A} & {r['id'] for r in B}
    cut = (len(A), len(B))
    A, B = [r for r in A if r['id'] in ids], [r for r in B if r['id'] in ids]
    ra, rb = unit_ratings(A, boot=args.boot, seed=1), unit_ratings(B, boot=args.boot, seed=2)
    common = [t for t in ra['types'] if t in rb['types']]
    print(f'run A: {len(A)} of {cut[0]} fights; run B: {len(B)} of {cut[1]} fights; {len(ids)} shared pairings; {len(common)} types in both')
    if args.focus:
        # The changed type would drag the sum-to-0 anchor: re-anchor both runs on the unchanged types (they sum to 0), and take the
        # SEs from the bootstrap samples re-anchored the same way.
        for res in (ra, rb):
            k = len(res['types'])
            keep = [i for i, t in enumerate(res['types']) if t != args.focus]
            res['r'] = res['r'] - res['r'][keep].mean()
            S = res['boot'][:, :k] - res['boot'][:, keep].mean(axis=1, keepdims=True)
            res['se'] = S.std(axis=0, ddof=1)
        print(f'ratings re-anchored so the types other than {args.focus} sum to 0 in each run')
    print(f'{"type":16s} {"A":>7s} {"B":>7s} {"B-A":>7s} {"SE":>6s} {"z":>6s}')
    zs = []
    for t in common:
        i, j = ra['types'].index(t), rb['types'].index(t)
        d = rb['r'][j] - ra['r'][i]
        se = math.hypot(ra['se'][i], rb['se'][j])
        z = d / se if se > 0 else float('nan')
        zs.append((t, z))
        flag = ' ***' if abs(z) > 3 else ' *' if abs(z) > 1.96 else ''
        print(f'{t:16s} {ra["r"][i]:+7.3f} {rb["r"][j]:+7.3f} {d:+7.3f} {se:6.3f} {z:+6.2f}{flag}')
    zz = np.array([z for _, z in zs])
    from scipy import stats
    print(f'types: {int(np.sum(np.abs(zz) <= 1.96))} of {len(zz)} within +/-1.96; sum z^2 = {np.sum(zz ** 2):.1f} on {len(zz)} df '
          f'(chi-square p = {1 - stats.chi2.cdf(np.sum(zz ** 2), len(zz)):.3f})')
    if not args.focus:
        print('(the ratings sum to 0, so a change to one type also moves the others by about 1/(k-1) of it; --focus re-anchors; the cells below have no such coupling)')
    ca, cb = pair_cells(A), pair_cells(B)
    focus = args.focus
    # Cell noise. With 4 to 8 fights a cell's own SE is too unsteady (and 0 where repeats came out the same), so by default one
    # per-fight SD is used for every cell: from the spread of the cell differences between two unchanged runs (--null-a, --null-b)
    # when given, else pooled over the cells of these two runs.
    sigma, how = None, 'own SE of each cell'
    if args.null_a and args.null_b:
        na, nb = pair_cells(duel_rows(split_paths(args.null_a))), pair_cells(duel_rows(split_paths(args.null_b)))
        scaled = [abs(nb[k]['m'] - na[k]['m']) / math.sqrt(1 / na[k]['n'] + 1 / nb[k]['n']) for k in set(na) & set(nb)]
        sigma = 1.4826 * float(np.median(scaled))
        how = f'empirical null: per-fight SD {sigma:.3f} from the median cell difference of the two unchanged runs ({len(scaled)} cells)'
    elif not args.own_se:
        ss, dof = 0.0, 0
        for run in (A, B):
            groups0 = collections.defaultdict(list)
            for r in run:
                if r['a'] != r['b']:
                    a, b = sorted((r['a'], r['b']))
                    s = r['side'] if r['a'] == a else -r['side']
                    groups0[(a, b, s)].append(r['m'] if r['a'] == a else -r['m'])  # within pairing and side, as in the bootstrap
            for v in groups0.values():
                v = np.array(v)
                ss += ((v - v.mean()) ** 2).sum()
                dof += len(v) - 1
        sigma = math.sqrt(ss / dof)
        how = f'per-fight SD pooled within pairing and side {sigma:.3f} ({dof} df)'
    print(f'cell noise: {how}')
    groups = {'with': [], 'without': []}
    for key in sorted(set(ca) & set(cb)):
        x, y = ca[key], cb[key]
        if sigma is not None:
            se = sigma * math.sqrt(1 / x['n'] + 1 / y['n'])
        else:
            if x['n'] < 2 or y['n'] < 2:
                continue
            se = math.hypot(x['se'], y['se'])
        if not se > 0:
            continue
        z = (y['m'] - x['m']) / se
        sign = -1 if focus and key[1] == focus else 1  # cells with the focus type read from its side
        groups['with' if focus and focus in key else 'without'].append((key, sign * (y['m'] - x['m']), sign * z))
    for name, g in groups.items():
        if not g:
            continue
        z = np.array([v[2] for v in g])
        k = int(np.sum(np.abs(z) > 1.96))
        p = 1 - stats.binom.cdf(k - 1, len(z), 0.05) if k else 1.0
        label = f'cells {name} {focus}' if focus else 'cells'
        print(f'{label}: {len(z)} cells, mean change {np.mean([v[1] for v in g]):+.3f}, {k} with |z| > 1.96 (expected {0.05 * len(z):.1f}; '
              f'binomial p of that many or more = {p:.3f}), sum z^2 = {np.sum(z ** 2):.1f} on {len(z)} df (p = {1 - stats.chi2.cdf(np.sum(z ** 2), len(z)):.3f})')
        if focus and name == 'with':
            up = sum(1 for v in g if v[1] > 0)
            print(f'    {up} of {len(g)} cells moved in {focus}\'s favour (sign test p = {1 - stats.binom.cdf(up - 1, len(g), 0.5):.5f})')
            for key, d, zz1 in sorted(g, key=lambda v: -abs(v[2])):
                other = key[0] if key[1] == focus else key[1]
                print(f'    {focus} vs {other:15s} change in {focus}\'s margin {d:+.3f} (z {zz1:+.2f})')


# ---------------------------------------------------------------- round robin

def rr_rows(paths):
    """(team-0 entrant, team-1 entrant, team-0 result 1/0.5/0, team-0 gap) from botsim results.csv or duel duels.csv clashes."""
    out = []
    for r in read_csv(paths):
        if 'banner0' in r:
            if r['winner'] == 'aborted':
                continue
            y = 1.0 if r['winner'] == 'dawn' else 0.0 if r['winner'] == 'dusk' else 0.5
            out.append((r['banner0'], r['banner1'], y, float(r['dawnScore']) - float(r['duskScore'])))
        elif 'aLineup' in r:
            if r['winner'] == 'aborted' or not r['aLineup'].startswith('banner:'):
                continue
            a, b = r['aLineup'][7:], r['bLineup'][7:]
            ya = 1.0 if r['winner'] == 'a' else 0.0 if r['winner'] == 'b' else 0.5
            m = float(r['margin'])
            if r['aSide'] == 'west':
                out.append((a, b, ya, m))
            else:
                out.append((b, a, 1 - ya, -m))
    return out


def bt_fit(rows, names, prior_sd=3.0):
    k = len(names)
    idx = {n: i for i, n in enumerate(names)}
    C = np.vstack([np.eye(k - 1), -np.ones(k - 1)])  # sum-to-zero contrasts
    X = np.zeros((len(rows), k))
    y = np.array([r[2] for r in rows])
    for n, r in enumerate(rows):
        if r[0] != r[1]:
            X[n, idx[r[0]]] += 1
            X[n, idx[r[1]]] -= 1
    D = np.hstack([X @ C, np.ones((len(rows), 1))])
    # A weak normal prior (SD prior_sd on each rating, 3 on the seat term) keeps the fit finite when a House wins or loses every
    # round (complete separation); with a few wins and losses per pair it hardly moves the estimate.
    P = np.zeros((D.shape[1], D.shape[1]))
    P[:-1, :-1] = C.T @ C / prior_sd ** 2
    P[-1, -1] = 1 / 9
    theta = np.zeros(D.shape[1])
    for _ in range(200):
        p = 1 / (1 + np.exp(-(D @ theta)))
        W = p * (1 - p)
        H = D.T @ (D * W[:, None]) + P
        step = np.linalg.solve(H, D.T @ (y - p) - P @ theta)
        theta += step
        if np.max(np.abs(step)) < 1e-10:
            break
    p = 1 / (1 + np.exp(-(D @ theta)))
    H = D.T @ (D * (p * (1 - p))[:, None]) + P
    cov = np.linalg.inv(H)
    s = C @ theta[:-1]
    cov_s = C @ cov[:-1, :-1] @ C.T
    eps = 1e-12
    ll = np.sum(y * np.log(p + eps) + (1 - y) * np.log(1 - p + eps))
    return s, np.sqrt(np.diag(cov_s)), theta[-1], math.sqrt(cov[-1, -1]), ll


def saturated_ll(rows):
    """One free share per unordered pair plus the common seat term, by the same Newton method."""
    pairs = sorted({tuple(sorted(r[:2])) for r in rows if r[0] != r[1]})
    pidx = {p: i for i, p in enumerate(pairs)}
    D = np.zeros((len(rows), len(pairs) + 1))
    y = np.array([r[2] for r in rows])
    for n, r in enumerate(rows):
        if r[0] != r[1]:
            key = tuple(sorted(r[:2]))
            D[n, pidx[key]] = 1 if r[0] == key[0] else -1
        D[n, -1] = 1
    theta = np.zeros(D.shape[1])
    for _ in range(200):
        p = 1 / (1 + np.exp(-(D @ theta)))
        H = D.T @ (D * (p * (1 - p))[:, None]) + 1e-6 * np.eye(D.shape[1])
        step = np.linalg.solve(H, D.T @ (y - p))
        theta += step
        if np.max(np.abs(step)) < 1e-10:
            break
    p = np.clip(1 / (1 + np.exp(-(D @ theta))), 1e-12, 1 - 1e-12)
    return np.sum(y * np.log(p) + (1 - y) * np.log(1 - p)), len(pairs)


def additive_gap(rows, names):
    k = len(names)
    idx = {n: i for i, n in enumerate(names)}
    X = np.zeros((len(rows) + 1, k + 1))
    y = np.zeros(len(rows) + 1)
    for n, r in enumerate(rows):
        if r[0] != r[1]:
            X[n, idx[r[0]]] += 1
            X[n, idx[r[1]]] -= 1
        X[n, k] = 1
        y[n] = r[3]
    X[-1, :k] = 1
    coef, *_ = np.linalg.lstsq(X, y, rcond=None)
    resid = y[:-1] - X[:-1] @ coef
    dof = max(1, len(rows) - k)
    sigma2 = resid @ resid / dof
    cov = sigma2 * np.linalg.pinv(X[:-1].T @ X[:-1] + np.outer(X[-1], X[-1]))
    return coef[:k], np.sqrt(np.diag(cov))[:k], coef[k], math.sqrt(cov[k, k])


def wilson(w, n, z=1.96):
    if n == 0:
        return float('nan'), float('nan')
    p = w / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return c - h, c + h


def report_rr(args):
    rows = rr_rows(args.files)
    if not rows:
        sys.exit('no rounds')
    names = sorted({r[0] for r in rows} | {r[1] for r in rows})
    from scipy import stats
    print(f'rounds={len(rows)} entrants={len(names)}')
    pairs = collections.defaultdict(lambda: [0.0, 0])
    for r in rows:
        if r[0] == r[1]:
            continue
        a, b = sorted(r[:2])
        pairs[(a, b)][0] += r[2] if r[0] == a else 1 - r[2]
        pairs[(a, b)][1] += 1
    for (a, b), (w, n) in sorted(pairs.items()):
        lo, hi = wilson(w, n)
        print(f'  {a:22s} vs {b:22s} {a} won {w:g} of {n} = {100 * w / n:5.1f}%  (95% {100 * lo:.0f} to {100 * hi:.0f})')
    mirror = [r for r in rows if r[0] == r[1]]
    if mirror:
        w = sum(r[2] for r in mirror)
        lo, hi = wilson(w, len(mirror))
        print(f'  mirrors: team 0 won {w:g} of {len(mirror)} = {100 * w / len(mirror):.1f}% (95% {100 * lo:.0f} to {100 * hi:.0f})')
    s, se, h, hse, ll = bt_fit(rows, names)
    print(f'\nBradley-Terry (logit scale, sum 0), seat term h={h:+.3f} (SE {hse:.3f}; team 0 wins {100 / (1 + math.exp(-h)):.0f}% of an even pairing)')
    for i in np.argsort(-s):
        p_avg = np.mean([1 / (1 + math.exp(-(s[i] - s[j]))) for j in range(len(names)) if j != i])
        print(f'  {names[i]:22s} s={s[i]:+.3f} (SE {se[i]:.3f}, 95% {s[i] - 1.96 * se[i]:+.2f} to {s[i] + 1.96 * se[i]:+.2f}); '
              f'expected share against the others {100 * p_avg:.0f}%')
    sll, npairs = saturated_ll(rows)
    df = npairs - (len(names) - 1)
    if df > 0:
        lr = 2 * (sll - ll)
        print(f'  fit: one rating per entrant vs one share per pair: LR={lr:.2f} on {df} df, p={1 - stats.chi2.cdf(lr, df):.3f} '
              f'(a small p means the pairs are not explained by one rating each, e.g. a counter cycle)')
    g, gse, gh, ghse = additive_gap(rows, names)
    unit = 'score' if any('banner0' in r for r in read_csv(args.files[:1])) else 'margin'
    print(f'\nadditive {unit} gap model (team 0 minus team 1), seat term {gh:+.2f} (SE {ghse:.2f}):')
    for i in np.argsort(-g):
        print(f'  {names[i]:22s} {g[i]:+7.2f} (SE {gse[i]:.2f})')


def match_view(paths, focus):
    """Per match from the focus banner's side: map, win (1/0.5/0), score gap, own kills, enemy kills, seat (0 dawn, 1 dusk)."""
    out = []
    for r in read_csv(paths):
        if r['winner'] == 'aborted' or focus not in (r['banner0'], r['banner1']):
            continue
        seat = 0 if r['banner0'] == focus else 1
        me, foe = ('dawn', 'dusk') if seat == 0 else ('dusk', 'dawn')
        win = 1.0 if r['winner'] == me else 0.0 if r['winner'] == foe else 0.5
        out.append(dict(map=r['map'], seat=seat, win=win, gap=float(r[me + 'Score']) - float(r[foe + 'Score']),
                        kills=float(r[me + 'Kills']), lost=float(r[foe + 'Kills']), seconds=float(r['seconds'])))
    return out


def compare_matches(args):
    """Two sets of bot matches of the same pairing (for example fast ticks against real time): each measure's difference,
    stratified by map and seat (the mean of the per-cell differences, so a different map mix cannot fake a difference)."""
    from scipy import stats
    A, B = match_view(split_paths(args.a), args.focus), match_view(split_paths(args.b), args.focus)
    print(f'{args.focus}: run A {len(A)} matches, run B {len(B)} matches')
    for key in ('win', 'gap', 'kills', 'lost', 'seconds'):
        xa, xb = np.array([m[key] for m in A]), np.array([m[key] for m in B])
        cells = sorted({(m['map'], m['seat']) for m in A} & {(m['map'], m['seat']) for m in B})

        def pooled(run):  # within-cell variance pooled over the cells (few matches per cell)
            groups = [np.array([m[key] for m in run if (m['map'], m['seat']) == c]) for c in cells]
            ss = sum(((g - g.mean()) ** 2).sum() for g in groups)
            dof = sum(len(g) - 1 for g in groups)
            return ss / dof if dof > 0 else 0.0
        va, vb = pooled(A), pooled(B)
        diffs, var = [], 0.0
        for c in cells:
            ca = np.array([m[key] for m in A if (m['map'], m['seat']) == c])
            cb = np.array([m[key] for m in B if (m['map'], m['seat']) == c])
            diffs.append(cb.mean() - ca.mean())
            var += va / len(ca) + vb / len(cb)
        d = float(np.mean(diffs)) if diffs else float('nan')
        se = math.sqrt(var) / len(cells) if cells else float('nan')
        t = stats.ttest_ind(xb, xa, equal_var=False) if xa.std() + xb.std() > 0 else None
        print(f'  {key:8s} A {xa.mean():7.2f} (SD {xa.std(ddof=1):5.2f})  B {xb.mean():7.2f} (SD {xb.std(ddof=1):5.2f})  '
              f'B-A by map and seat {d:+6.2f} (95% {d - 1.96 * se:+.2f} to {d + 1.96 * se:+.2f}, {len(cells)} cells)'
              + (f'  Welch p={t.pvalue:.3f}' if t is not None else '  (no variation)'))


