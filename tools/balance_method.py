def report_types(args):
    T = troops()
    rows = read_csv(args.files)
    side_key = 'banner' if 'banner' in rows[0] else 'lineup'
    unit_key = 'match' if 'match' in rows[0] else 'fight'
    seat_key = 'seat' if 'seat' in rows[0] else 'role'
    agg = collections.defaultdict(lambda: collections.defaultdict(float))
    rounds = collections.defaultdict(set)
    side_dealt = collections.defaultdict(float)
    per_round = collections.defaultdict(dict)
    overflow = 0
    for r in rows:
        key = (r[side_key], r['troop'])
        rnd = (r['_file'], r[unit_key], r[seat_key])
        rounds[r[side_key]].add(rnd)
        a = agg[key]
        for c in ('fielded', 'opening', 'bought', 'deaths', 'rises', 'kills', 'killGold', 'dealt', 'taken', 'takenOther', 'healed', 'hits'):
            a[c] += float(r[c] or 0)
        if r['meanFactor']:
            a['factorSum'] += float(r['meanFactor']) * float(r['hits'])
        if r['firstKillSecond']:
            a['firstKill'] += float(r['firstKillSecond'])
            a['firstKillN'] += 1
        side_dealt[(r[side_key], rnd)] += float(r['dealt'] or 0)
        cost = T[r['troop']]['cost'] if r['troop'] in T else 0
        per_round[key][rnd] = (float(r['dealt'] or 0), float(r['fielded'] or 0) * cost)
        overflow = max(overflow, int(r['overflowTicks'] or 0))
    print(f'{len(rows)} rows; per-round means; most 64-blow-log overflow ticks in one round: {overflow}')
    rng = np.random.default_rng(3)

    def ratio_ci(key):  # 95% bootstrap interval of dealt per gold fielded, resampling rounds
        v = np.array(list(per_round[key].values()))
        if len(v) < 2 or v[:, 1].sum() == 0:
            return float('nan'), float('nan')
        idx = rng.integers(0, len(v), (500, len(v)))
        s = v[idx].sum(axis=1)
        q = s[:, 0] / np.maximum(s[:, 1], 1e-9)
        return np.percentile(q, 2.5), np.percentile(q, 97.5)
    print(f'{"side":28s} {"troop":15s} {"fielded":>7s} {"bought":>6s} {"deaths":>6s} {"kills":>6s} {"killGold/gold":>13s} {"dealt":>7s} {"dealt/gold":>10s} '
          f'{"95%":>11s} {"share":>6s} {"factor":>6s} {"1st kill s":>10s} {"rises":>5s} {"healed":>6s}')
    for side in sorted(rounds):
        n = len(rounds[side])
        total = sum(v for (s, _), v in side_dealt.items() if s == side) / n
        for (s, troop), a in sorted(agg.items(), key=lambda kv: -kv[1]['dealt']):
            if s != side:
                continue
            gold = a['fielded'] * T[troop]['cost'] if troop in T else float('nan')
            factor = a['factorSum'] / a['hits'] if a['hits'] else float('nan')
            first = a['firstKill'] / a['firstKillN'] if a['firstKillN'] else float('nan')
            lo, hi = ratio_ci((s, troop))
            print(f'{side:28s} {troop:15s} {a["fielded"] / n:7.1f} {a["bought"] / n:6.1f} {a["deaths"] / n:6.1f} {a["kills"] / n:6.1f} '
                  f'{a["killGold"] / gold:13.2f} {a["dealt"] / n:7.0f} {a["dealt"] / gold:10.2f} {lo:5.2f}-{hi:4.2f} {100 * a["dealt"] / n / total if total else 0:5.0f}% '
                  f'{factor:6.2f} {first:10.1f} {a["rises"] / n:5.1f} {a["healed"] / n:6.0f}')
        print(f'{side:28s} {"(rounds)":15s} {n}')
    if args.results:
        res = read_csv(args.results)
        bad = 0
        deaths = collections.defaultdict(float)
        for r in rows:
            deaths[(r['_file'].replace('types.csv', 'results.csv'), r['match'], r['seat'])] += float(r['deaths'])
        checked = 0
        for r in res:
            for seat, other in (('dawn', 'dusk'), ('dusk', 'dawn')):
                key = (r['_file'], r['match'], other)
                if key not in deaths:
                    continue
                checked += 1
                if int(deaths[key]) != int(r[seat + 'Kills']):
                    bad += 1
                    print(f'  mismatch {r["_file"]} match {r["match"]}: results {seat}Kills={r[seat + "Kills"]}, ledger {other} deaths={deaths[key]:g}')
        print(f'reconciliation: {checked} side-rounds checked against results.csv kills, {bad} mismatches')


