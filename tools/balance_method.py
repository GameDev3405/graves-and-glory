def gate(_args):
    from scipy import stats
    print('The current gate: n = 20 decided matches, pass when 8 <= wins <= 12 (40 to 60%), draws ignored here.')
    for p in (0.3, 0.35, 0.4, 0.45, 0.5, 0.55, 0.6, 0.65, 0.7):
        pas = stats.binom.cdf(12, 20, p) - stats.binom.cdf(7, 20, p)
        print(f'  true share {p:.2f}: passes {100 * pas:5.1f}% of the time')
    for n in (20, 40, 100, 200, 400):
        print(f'  n={n:4d}: 95% half-width at 50% = {100 * 1.96 * math.sqrt(0.25 / n):5.1f} points')
    for h in (10, 5):
        print(f'  half-width {h} points needs n = {math.ceil((1.96 / (h / 100)) ** 2 * 0.25)} decided matches')


